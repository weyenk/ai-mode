// ---- process helpers -------------------------------------------------------

func pidAlive(pid int) bool {
	if pid <= 0 {
		return false
	}
	err := syscall.Kill(pid, 0)
	return err == nil || err == syscall.EPERM
}

func portOpen(host string, port int) bool {
	c, err := net.DialTimeout("tcp", net.JoinHostPort(host, strconv.Itoa(port)), 400*time.Millisecond)
	if err != nil {
		return false
	}
	c.Close()
	return true
}

func findLlamaServer() string {
	for _, c := range []string{
		filepath.Join(homeDir, ".local", "bin", "llama-server"),
		"/opt/homebrew/bin/llama-server",
		"/usr/local/bin/llama-server",
	} {
		if st, err := os.Stat(c); err == nil && st.Mode().IsRegular() && st.Mode()&0o111 != 0 {
			return c
		}
	}
	if p, err := exec.LookPath("llama-server"); err == nil {
		return p
	}
	return ""
}

// managedPID returns the recorded pid if that process is still alive.
func managedPID(st State) int {
	if pidAlive(st.PID) {
		return st.PID
	}
	return 0
}

// stopManaged SIGTERMs the managed server, escalating to SIGKILL after wait.
func stopManaged(st *State, wait time.Duration) bool {
	clear := func() {
		st.PID = 0
		saveState(*st)
	}
	if !pidAlive(st.PID) {
		clear()
		return true
	}
	if err := syscall.Kill(st.PID, syscall.SIGTERM); err == syscall.ESRCH {
		clear()
		return true
	}
	deadline := time.Now().Add(wait)
	for time.Now().Before(deadline) {
		if !pidAlive(st.PID) {
			clear()
			return true
		}
		time.Sleep(150 * time.Millisecond)
	}
	_ = syscall.Kill(st.PID, syscall.SIGKILL)
	time.Sleep(200 * time.Millisecond)
	if !pidAlive(st.PID) {
		clear()
		return true
	}
	return false
}

